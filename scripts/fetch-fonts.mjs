// Fetch the approved OFL fonts from the official Google Fonts open-source
// repository (the publishers' OFL distribution channel), verify they are real
// TrueType files, record their SHA-256, install the OFL license texts, and
// write src/fonts.generated.css. Fonts are never committed to this repository.
//
//   node scripts/fetch-fonts.mjs
//
// Environment: FONT_BASE_URL may point at a mirror of github.com/google/fonts (raw).
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const BASE = process.env.FONT_BASE_URL ?? 'https://raw.githubusercontent.com/google/fonts/main';
const FONTS = [
  { family: 'Cormorant Garamond', src: 'ofl/cormorantgaramond/CormorantGaramond%5Bwght%5D.ttf', out: 'CormorantGaramond-VF.ttf', style: 'normal', weight: '300 700' },
  { family: 'Source Sans 3', src: 'ofl/sourcesans3/SourceSans3%5Bwght%5D.ttf', out: 'SourceSans3-VF.ttf', style: 'normal', weight: '200 900' },
  { family: 'Source Sans 3', src: 'ofl/sourcesans3/SourceSans3-Italic%5Bwght%5D.ttf', out: 'SourceSans3-Italic-VF.ttf', style: 'italic', weight: '200 900' },
];
const LICENSES = [
  { src: 'ofl/cormorantgaramond/OFL.txt', out: 'OFL-CormorantGaramond.txt' },
  { src: 'ofl/sourcesans3/OFL.txt', out: 'OFL-SourceSans3.txt' },
];

const pub = join(root, 'public/fonts');
const lic = join(root, 'LICENSES/fonts');
mkdirSync(pub, { recursive: true });
mkdirSync(lic, { recursive: true });

async function get(path) {
  const url = `${BASE}/${path}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return { url, buf: Buffer.from(await res.arrayBuffer()) };
}

const manifest = { source: BASE, fetchedAt: new Date().toISOString(), files: [] };
for (const f of FONTS) {
  const { url, buf } = await get(f.src);
  const magic = buf.readUInt32BE(0);
  if (magic !== 0x00010000 && magic !== 0x74727565) throw new Error(`${f.out} is not a TrueType font (magic ${magic.toString(16)})`);
  writeFileSync(join(pub, f.out), buf);
  manifest.files.push({ file: f.out, family: f.family, url, bytes: buf.length, sha256: createHash('sha256').update(buf).digest('hex') });
  console.log(`fetched ${f.out} (${(buf.length / 1024).toFixed(0)} KiB)`);
}
for (const l of LICENSES) {
  const { url, buf } = await get(l.src);
  const text = buf.toString('utf8');
  if (!/SIL OPEN FONT LICENSE/i.test(text)) throw new Error(`${l.out} does not look like the SIL OFL`);
  writeFileSync(join(pub, l.out), text);
  writeFileSync(join(lic, l.out), text);
  manifest.files.push({ file: l.out, url, bytes: buf.length, sha256: createHash('sha256').update(buf).digest('hex') });
  console.log(`fetched ${l.out}`);
}
writeFileSync(join(pub, 'fonts-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
writeFileSync(
  join(root, 'src/fonts.generated.css'),
  `/* Generated by scripts/fetch-fonts.mjs — SIL Open Font License 1.1 (see /fonts/OFL-*.txt). */\n` +
    FONTS.map(
      (f) => `@font-face {\n  font-family: '${f.family}';\n  src: url('/fonts/${f.out}') format('truetype');\n  font-weight: ${f.weight};\n  font-style: ${f.style};\n  font-display: swap;\n}\n`,
    ).join(''),
);
console.log('Fonts installed; src/fonts.generated.css written.');
